"""
NIRMAN AI — Blender Code Generator
Converts a validated BuildingSpec dict into a self-contained Blender Python
script string. All values are substituted at generation time — no runtime
template variables. The script imports the geometry kernel and builds the
3D building step by step with full error reporting.
"""
from __future__ import annotations
import json
import textwrap
from pathlib import Path
from typing import Optional


class BlenderCodeGenerator:
    """
    Generates a complete, runnable Blender Python script from a BuildingSpec dict.

    Usage:
        gen    = BlenderCodeGenerator()
        script = gen.generate_script(spec_dict, "/out/building.gltf", "/out/building.blend")
        # Write script to file, then: blender --background --python <script>.py
    """

    def __init__(self, kernel_path: Optional[str] = None) -> None:
        # Root of the nirman_ai package (two levels up from this file)
        self.kernel_path = kernel_path or str(Path(__file__).parent.parent.parent)

    # ------------------------------------------------------------------
    # Public API
    # ------------------------------------------------------------------

    def generate_script(
        self,
        spec: dict,
        output_gltf_path: str,
        output_blend_path: str,
    ) -> str:
        """Return a complete Blender Python script string for this spec."""
        lines: list[str] = []
        lines += self._header()
        lines += self._imports()
        lines += ["", "try:"]
        lines += self._body(spec, output_gltf_path, output_blend_path)
        lines += self._error_handler()
        return "\n".join(lines)

    # ------------------------------------------------------------------
    # Script sections
    # ------------------------------------------------------------------

    def _header(self) -> list[str]:
        return [
            "#!/usr/bin/env python3",
            "# NIRMAN AI — Auto-generated Blender building script",
            "# Generated by nirman.kernel.codegen.BlenderCodeGenerator",
            "# Run with: blender --background --python <this_file>.py",
            "",
        ]

    def _imports(self) -> list[str]:
        pkg_root = repr(str(Path(self.kernel_path)))
        return [
            "import sys, json, traceback",
            f"sys.path.insert(0, {pkg_root})",
            "",
            "from nirman.kernel.geometry import (",
            "    clear_scene, create_floor_slab, create_room,",
            "    create_staircase, punch_stairwell_hole,",
            "    create_roof, setup_lighting_and_camera,",
            "    export_gltf, save_blend,",
            ")",
        ]

    def _body(
        self, spec: dict, gltf: str, blend: str
    ) -> list[str]:
        ind = "    "   # inside try block
        lines: list[str] = []

        rooms      = spec.get("rooms", [])
        staircases = spec.get("staircases", [])
        num_floors = spec.get("num_floors", 1)
        roof       = spec.get("roof", {})

        # Building bounding box (for slab dimensions)
        all_x = [r["position"]["x"] + r["dimensions"]["width"]  for r in rooms] or [10.0]
        all_y = [r["position"]["y"] + r["dimensions"]["depth"]   for r in rooms] or [10.0]
        max_x = max(all_x)
        max_y = max(all_y)

        lines.append(f"{ind}clear_scene()")
        lines.append("")

        # ── Floor slabs ───────────────────────────────────────────────
        lines.append(f"{ind}# ─── Floor slabs ───")
        for lvl in range(num_floors):
            # Pick first staircase starting at this floor for hole
            hole_arg = "None"
            for st in staircases:
                if st.get("from_floor") == lvl and lvl + 1 < num_floors:
                    pos = st.get("position", {"x": 0, "y": 0})
                    ow  = st.get("opening_width",  1.2)
                    od  = st.get("opening_depth",  2.5)
                    hole_arg = (
                        f'{{"x": {pos["x"]:.3f}, "y": {pos["y"]:.3f},'
                        f' "w": {ow:.3f}, "d": {od:.3f}}}'
                    )
                    break
            lines.append(
                f"{ind}create_floor_slab("
                f"level={lvl}, x=0.0, y=0.0, "
                f"width={max_x:.3f}, depth={max_y:.3f}, "
                f"stair_hole={hole_arg})"
            )
        lines.append("")

        # ── Rooms ─────────────────────────────────────────────────────
        lines.append(f"{ind}# ─── Rooms ───")
        for room in rooms:
            rid  = room["id"]
            fl   = room.get("floor", 0)
            dims = room.get("dimensions", {})
            pos  = room.get("position",   {})
            dws  = room.get("doorways",   [])
            wins = room.get("windows",    [])
            lines.append(
                f"{ind}create_room("
                f"room_id={rid!r}, floor_level={fl}, "
                f"x={pos.get('x', 0):.3f}, y={pos.get('y', 0):.3f}, "
                f"width={dims.get('width', 4):.3f}, depth={dims.get('depth', 4):.3f}, "
                f"wall_height={dims.get('height', 3.0):.3f}, "
                f"doorways={json.dumps(dws)}, "
                f"windows={json.dumps(wins)})"
            )
        lines.append("")

        # ── Staircases ────────────────────────────────────────────────
        lines.append(f"{ind}# ─── Staircases ───")
        for st in staircases:
            sid = st["id"]
            ff  = st.get("from_floor", 0)
            tf  = st.get("to_floor",   1)
            pos = st.get("position",   {"x": 0, "y": 0})
            drn = st.get("direction",  "north")
            w   = st.get("width",      1.0)
            ow  = st.get("opening_width",  1.2)
            od  = st.get("opening_depth",  2.5)
            lines.append(
                f"{ind}create_staircase("
                f"stair_id={sid!r}, from_floor={ff}, to_floor={tf}, "
                f"x={pos['x']:.3f}, y={pos['y']:.3f}, "
                f"direction={drn!r}, stair_width={w:.3f})"
            )
            lines.append(
                f"{ind}punch_stairwell_hole("
                f"floor_level={tf}, "
                f"hole_x={pos['x']:.3f}, hole_y={pos['y']:.3f}, "
                f"hole_w={ow:.3f}, hole_d={od:.3f})"
            )
        lines.append("")

        # ── Roof ──────────────────────────────────────────────────────
        lines.append(f"{ind}# ─── Roof ───")
        r_type  = roof.get("type",          "flat")
        r_pitch = roof.get("pitch_degrees") or 20.0
        lines.append(
            f"{ind}create_roof("
            f"x=0.0, y=0.0, width={max_x:.3f}, depth={max_y:.3f}, "
            f"top_floor={num_floors - 1}, "
            f"roof_type={r_type!r}, pitch_degrees={r_pitch:.1f})"
        )
        lines.append("")

        # ── Lighting + camera ─────────────────────────────────────────
        lines.append(f"{ind}# ─── Lighting & camera ───")
        lines.append(
            f"{ind}setup_lighting_and_camera("
            f"building_width={max_x:.3f}, building_depth={max_y:.3f}, "
            f"num_floors={num_floors})"
        )
        lines.append("")

        # ── Export ────────────────────────────────────────────────────
        lines.append(f"{ind}# ─── Export ───")
        lines.append(f"{ind}export_gltf({gltf!r})")
        lines.append(f"{ind}save_blend({blend!r})")
        lines.append(f"{ind}print('NIRMAN_SUCCESS')")

        return lines

    def _error_handler(self) -> list[str]:
        return [
            "",
            "except Exception as _e:",
            "    import json as _j",
            "    print('NIRMAN_ERROR:' + _j.dumps({",
            "        'error': str(_e),",
            "        'traceback': traceback.format_exc()",
            "    }))",
            "    raise",
        ]
