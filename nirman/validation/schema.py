"""
NIRMAN AI — Building Specification Schema
Pydantic v2 models for the structured JSON generated by the VLM planner.
Every field carries a confidence level: measured | inferred | assumed.
"""
from __future__ import annotations
from enum import Enum
from typing import Literal, Optional
from pydantic import BaseModel, Field, field_validator, model_validator


# ---------------------------------------------------------------------------
# Enums
# ---------------------------------------------------------------------------

class ConfidenceLevel(str, Enum):
    MEASURED = "measured"
    INFERRED = "inferred"
    ASSUMED  = "assumed"


class RoomType(str, Enum):
    LIVING_ROOM = "living_room"
    BEDROOM     = "bedroom"
    KITCHEN     = "kitchen"
    BATHROOM    = "bathroom"
    CORRIDOR    = "corridor"
    STAIRCASE   = "staircase"
    LOBBY       = "lobby"
    OFFICE      = "office"
    STORAGE     = "storage"
    TERRACE     = "terrace"
    OTHER       = "other"


class Direction(str, Enum):
    NORTH = "north"
    SOUTH = "south"
    EAST  = "east"
    WEST  = "west"


# ---------------------------------------------------------------------------
# Primitive geometry types
# ---------------------------------------------------------------------------

class Position2D(BaseModel):
    x: float
    y: float


class Dimensions3D(BaseModel):
    width:  float = Field(gt=0, description="Width in metres (X axis)")
    depth:  float = Field(gt=0, description="Depth in metres (Y axis)")
    height: float = Field(gt=0, description="Height in metres (Z axis)")


# ---------------------------------------------------------------------------
# Opening specs
# ---------------------------------------------------------------------------

class DoorwaySpec(BaseModel):
    """A usable door passage between two rooms."""
    to_room_id:           str
    width:                float     = Field(default=0.9, ge=0.8,  description="Min 0.8 m clearance")
    height:               float     = Field(default=2.1, ge=2.0,  description="Min 2.0 m clearance")
    wall_side:            Direction = Direction.SOUTH
    position_along_wall:  float     = Field(default=0.5, ge=0.0, le=1.0)
    confidence:           ConfidenceLevel = ConfidenceLevel.ASSUMED


class WindowSpec(BaseModel):
    width:               float     = Field(gt=0)
    height:              float     = Field(gt=0)
    sill_height:         float     = Field(default=0.9, ge=0.3)
    wall_side:           Direction = Direction.SOUTH
    position_along_wall: float     = Field(default=0.5, ge=0.0, le=1.0)
    confidence:          ConfidenceLevel = ConfidenceLevel.ASSUMED


# ---------------------------------------------------------------------------
# Room
# ---------------------------------------------------------------------------

class RoomSpec(BaseModel):
    id:         str
    type:       RoomType
    floor:      int           = Field(ge=0)
    dimensions: Dimensions3D
    position:   Position2D
    doorways:   list[DoorwaySpec] = Field(default_factory=list)
    windows:    list[WindowSpec]  = Field(default_factory=list)
    confidence: ConfidenceLevel   = ConfidenceLevel.ASSUMED
    is_entrance: bool = False
    notes:       Optional[str]    = None


# ---------------------------------------------------------------------------
# Staircase
# ---------------------------------------------------------------------------

class StaircaseSpec(BaseModel):
    id:            str
    from_floor:    int   = Field(ge=0)
    to_floor:      int   = Field(ge=0)
    position:      Position2D
    direction:     Direction
    width:         float = Field(default=1.0,   ge=0.9)
    run_depth:     float = Field(default=0.28,  ge=0.25)
    rise_height:   float = Field(default=0.175, le=0.22)
    num_steps:     Optional[int] = None
    opening_width: float = Field(default=1.2,   ge=1.0)
    opening_depth: float = Field(default=2.5,   ge=2.0)

    @field_validator("to_floor")
    @classmethod
    def to_differs_from_from(cls, v: int, info) -> int:
        if "from_floor" in info.data and v == info.data["from_floor"]:
            raise ValueError("to_floor must differ from from_floor")
        return v


# ---------------------------------------------------------------------------
# Wall
# ---------------------------------------------------------------------------

class WallSpec(BaseModel):
    id:        str
    floor:     int   = Field(ge=0)
    start:     Position2D
    end:       Position2D
    thickness: float = Field(default=0.2, gt=0)
    height:    float = Field(gt=0)


# ---------------------------------------------------------------------------
# Roof & Floor slab
# ---------------------------------------------------------------------------

class RoofSpec(BaseModel):
    type:                Literal["flat", "gabled", "hipped"] = "flat"
    pitch_degrees:       Optional[float] = Field(default=None, ge=0, le=60)
    has_terrace_access:  bool = False
    access_staircase_id: Optional[str]  = None


class FloorSpec(BaseModel):
    level:           int   = Field(ge=0)
    slab_thickness:  float = Field(default=0.2, gt=0)
    room_ids:        list[str] = Field(default_factory=list)


# ---------------------------------------------------------------------------
# Top-level building spec
# ---------------------------------------------------------------------------

class BuildingSpec(BaseModel):
    num_floors:        int   = Field(ge=1)
    floors:            list[FloorSpec]
    rooms:             list[RoomSpec]
    staircases:        list[StaircaseSpec]
    walls:             list[WallSpec]    = Field(default_factory=list)
    roof:              RoofSpec
    entrance_room_id:  str
    style_notes:       Optional[str]    = None
    source_confidence: ConfidenceLevel  = ConfidenceLevel.ASSUMED
    has_interior_photos: bool = False
    has_measurements:    bool = False

    # -----------------------------------------------------------------------
    # Cross-field validators
    # -----------------------------------------------------------------------

    @model_validator(mode="after")
    def _entrance_exists(self) -> "BuildingSpec":
        ids = {r.id for r in self.rooms}
        if self.entrance_room_id not in ids:
            raise ValueError(
                f"entrance_room_id '{self.entrance_room_id}' not found in rooms"
            )
        return self

    @model_validator(mode="after")
    def _doorway_targets_exist(self) -> "BuildingSpec":
        ids = {r.id for r in self.rooms}
        for room in self.rooms:
            for dw in room.doorways:
                if dw.to_room_id not in ids:
                    raise ValueError(
                        f"Room '{room.id}' doorway references unknown room '{dw.to_room_id}'"
                    )
        return self

    @model_validator(mode="after")
    def _staircase_floors_in_range(self) -> "BuildingSpec":
        max_f = self.num_floors - 1
        for st in self.staircases:
            if st.from_floor > max_f or st.to_floor > max_f:
                raise ValueError(
                    f"Staircase '{st.id}' references floor beyond num_floors={self.num_floors}"
                )
        return self

    @model_validator(mode="after")
    def _roof_staircase_exists(self) -> "BuildingSpec":
        if self.roof.access_staircase_id:
            ids = {s.id for s in self.staircases}
            if self.roof.access_staircase_id not in ids:
                raise ValueError(
                    f"roof.access_staircase_id '{self.roof.access_staircase_id}' not found"
                )
        return self

    @model_validator(mode="after")
    def _floor_room_ids_exist(self) -> "BuildingSpec":
        ids = {r.id for r in self.rooms}
        for fl in self.floors:
            for rid in fl.room_ids:
                if rid not in ids:
                    raise ValueError(
                        f"Floor {fl.level} references unknown room '{rid}'"
                    )
        return self

    # -----------------------------------------------------------------------
    # Helpers
    # -----------------------------------------------------------------------

    def get_room(self, room_id: str) -> Optional[RoomSpec]:
        for r in self.rooms:
            if r.id == room_id:
                return r
        return None
